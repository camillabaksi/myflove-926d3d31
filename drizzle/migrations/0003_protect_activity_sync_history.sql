CREATE TABLE public.user_kv_revisions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  key text NOT NULL,
  value jsonb NOT NULL,
  source_updated_at timestamptz,
  archived_at timestamptz NOT NULL DEFAULT now(),
  operation text NOT NULL CHECK (operation IN ('update', 'delete'))
);

GRANT SELECT ON public.user_kv_revisions TO authenticated;
GRANT ALL ON public.user_kv_revisions TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.user_kv_revisions_id_seq TO service_role;

ALTER TABLE public.user_kv_revisions ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can read own kv revisions"
ON public.user_kv_revisions
FOR SELECT
TO authenticated
USING (auth.uid() = user_id);

CREATE INDEX user_kv_revisions_lookup_idx
ON public.user_kv_revisions (user_id, key, archived_at DESC);

CREATE OR REPLACE FUNCTION public.archive_user_kv_revision()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'DELETE' OR OLD.value IS DISTINCT FROM NEW.value THEN
    INSERT INTO public.user_kv_revisions (user_id, key, value, source_updated_at, operation)
    VALUES (OLD.user_id, OLD.key, OLD.value, OLD.updated_at, lower(TG_OP));
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

CREATE TRIGGER archive_user_kv_before_change
BEFORE UPDATE OR DELETE ON public.user_kv
FOR EACH ROW EXECUTE FUNCTION public.archive_user_kv_revision();

CREATE TABLE public.child_item_revisions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id uuid NOT NULL,
  owner_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  snapshot jsonb NOT NULL,
  archived_at timestamptz NOT NULL DEFAULT now(),
  operation text NOT NULL CHECK (operation IN ('update', 'delete'))
);

GRANT SELECT ON public.child_item_revisions TO authenticated;
GRANT ALL ON public.child_item_revisions TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.child_item_revisions_id_seq TO service_role;

ALTER TABLE public.child_item_revisions ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can read own child item revisions"
ON public.child_item_revisions
FOR SELECT
TO authenticated
USING (auth.uid() = owner_id);

CREATE INDEX child_item_revisions_lookup_idx
ON public.child_item_revisions (owner_id, item_id, archived_at DESC);

CREATE OR REPLACE FUNCTION public.archive_child_item_revision()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'DELETE' OR to_jsonb(OLD) IS DISTINCT FROM to_jsonb(NEW) THEN
    INSERT INTO public.child_item_revisions (item_id, owner_id, snapshot, operation)
    VALUES (OLD.id, OLD.owner_id, to_jsonb(OLD), lower(TG_OP));
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

CREATE TRIGGER archive_child_item_before_change
BEFORE UPDATE OR DELETE ON public.child_items
FOR EACH ROW EXECUTE FUNCTION public.archive_child_item_revision();